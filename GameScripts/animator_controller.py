def animator_interface(type):
    """ Function for selecting animators """
    
    if type == "player":
        return PlayerAnimator(
            player_idle_camerafacing=player_idle_camerafacing, 
            player_idle_forward=player_idle_forward, 
            player_idle_left=player_idle_left,
            player_idle_leftTop = player_idle_leftTop,
            player_idle_leftBottom = player_idle_leftBottom,
            player_idle_right=player_idle_right,
            player_idle_rightTop = player_idle_rightTop,
            player_idle_rightBottom = player_idle_rightBottom,
            player_run_camerafacing=player_run_camerafacing, 
            player_run_forward=player_run_forward,
            player_run_left=player_run_left,
            player_run_leftTop = player_run_leftTop,
            player_run_leftBottom = player_run_leftBottom,
            player_run_right=player_run_right,
            player_run_rightTop = player_run_rightTop,
            player_run_rightBottom = player_run_rightBottom,
            player_shoot_camera = player_shoot_camera,
            player_shoot_forward = player_shoot_forward,
            player_shoot_left = player_shoot_left,
            player_shoot_leftBottom = player_shoot_leftBottom,
            player_shoot_leftTop = player_shoot_leftTop,
            player_shoot_right = player_shoot_right,
            player_shoot_rightBottom = player_shoot_rightBottom,
            player_shoot_rightTop = player_shoot_rightTop
        )
    elif type == "spider":
        return SpiderAnimator(
            spider_idle = spider_idle,
            spider_camera_facing = spider_camera_facing,
            spider_death = spider_death,
            spider_forward_facing = spider_forward_facing,
            spider_left_facing = spider_left_facing,
            spider_leftBottom_facing = spider_leftBottom_facing,
            spider_leftTop_facing = spider_leftTop_facing,
            spider_right_facing = spider_right_facing,
            spider_rightBottom_facing = spider_rightBottom_facing,
            spider_rightTop_facing = spider_rightTop_facing
        )
return 0